-- Teller application: accounts and the transfers entered at the teller screen.
CREATE TABLE ACCOUNT (
    ACCT_ID     DECIMAL(10,0) NOT NULL PRIMARY KEY,
    CUST_ID     INTEGER       NOT NULL,
    BALANCE     DECIMAL(11,2) NOT NULL,
    STATUS      CHAR(1)       NOT NULL
);

CREATE TABLE TRANSFER (
    TRF_ID      INTEGER       NOT NULL PRIMARY KEY,
    FROM_ACCT   DECIMAL(10,0) NOT NULL REFERENCES ACCOUNT (ACCT_ID),
    TO_ACCT     DECIMAL(10,0) NOT NULL REFERENCES ACCOUNT (ACCT_ID),
    AMOUNT      DECIMAL(9,2)  NOT NULL,
    TRF_TS      TIMESTAMP     NOT NULL
);

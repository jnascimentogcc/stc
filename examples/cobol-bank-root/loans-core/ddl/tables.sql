CREATE TABLE CUSTOMER (
    CUST_ID       DECIMAL(10)   NOT NULL PRIMARY KEY,
    BIRTH_DT      DECIMAL(8)    NOT NULL,
    MONTHLY_INC   DECIMAL(11,2) NOT NULL,
    CREDIT_SCORE  DECIMAL(4)    NOT NULL
);

CREATE TABLE CONTRACT (
    CONTR_ID      DECIMAL(10)   NOT NULL PRIMARY KEY,
    CUST_ID       DECIMAL(10)   NOT NULL REFERENCES CUSTOMER,
    PROD_CD       CHAR(2)       NOT NULL,
    PRINC_AMT     DECIMAL(13,2) NOT NULL,
    RATE_MO       DECIMAL(7,6)  NOT NULL,
    TERM_MO       DECIMAL(3)    NOT NULL,
    AMORT_TP      CHAR(1)       NOT NULL,
    START_DT      DATE          NOT NULL,
    STATUS        CHAR(1)       NOT NULL,
    DAYS_LATE     DECIMAL(5)    NOT NULL WITH DEFAULT 0
);

CREATE TABLE INSTALLMENT (
    CONTR_ID      DECIMAL(10)   NOT NULL REFERENCES CONTRACT,
    INST_NO       DECIMAL(3)    NOT NULL,
    DUE_DT        DATE          NOT NULL,
    INST_AMT      DECIMAL(13,2) NOT NULL,
    PAID_FLG      CHAR(1)       NOT NULL WITH DEFAULT 'N',
    PRIMARY KEY (CONTR_ID, INST_NO)
);

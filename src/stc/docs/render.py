"""Markdown of a documentation page, and recovery of the maintainers' corrections (DOC-06).

Every part ends up under its own heading with an empty manual block; whatever a maintainer writes
between the markers survives regeneration and is given to the model as authoritative for that part.
Each page also ends with a notes block that is shown as is and never sent to the model."""

import re
from collections.abc import Mapping
from dataclasses import dataclass

from stc.catalog.model import SectionResult
from stc.docs.model import Page, Part, Static

_MANUAL = re.compile(
    r"<!-- stc:manual:begin section=(\S+) -->\n?(.*?)\n?<!-- stc:manual:end -->", re.DOTALL
)
NOTES = "notes"
NOT_GENERATED = (
    "_Not generated yet: run this command again with a model configured to write this part._"
)


@dataclass(frozen=True)
class RenderMeta:
    code_version: str | None
    generated_at: str
    provider: str
    model: str
    language: str


def parse_manual_blocks(markdown: str) -> dict[str, str]:
    """Block key -> text written by maintainers (empty blocks are omitted)."""
    return {
        m.group(1): m.group(2).strip() for m in _MANUAL.finditer(markdown) if m.group(2).strip()
    }


def manual_block(key: str, text: str) -> str:
    return f"<!-- stc:manual:begin section={key} -->\n{text}\n<!-- stc:manual:end -->"


_LEADING_NUMBER = re.compile(r"^\(?\d+[.)]\s+")


def render_claims(result: SectionResult, style: str) -> str:
    lines: list[str] = []
    for number, claim in enumerate(result.claims, 1):
        evidence = ", ".join(f"`{e}`" for e in claim.evidence)
        confidence = "" if claim.confidence == "high" else f" _({claim.confidence} confidence)_"
        # The model sometimes numbers its own steps; the numbering here is the one that counts.
        said = _LEADING_NUMBER.sub("", claim.text) if style == "steps" else claim.text
        text = f"{said}{confidence} (evidence: {evidence})"
        lines.append(f"{number}. {text}" if style == "steps" else text)
        if style != "steps":
            lines.append("")
    body = "\n".join(lines).rstrip()
    if result.gaps:
        body += ("\n\n" if body else "") + "**Gaps**\n\n" + "\n".join(f"- {g}" for g in result.gaps)
    return body or "_Nothing could be determined._"


def render_page(
    page: Page,
    meta: RenderMeta,
    status: str,
    parts: Mapping[str, str],
    manual: Mapping[str, str],
) -> str:
    """`parts` maps a part id to its markdown body (claims, or the not-generated note)."""
    out = [
        f"# {page.title}",
        "",
        f"> Generated by STC from code version `{meta.code_version or 'unknown'}` on "
        f"{meta.generated_at} with {meta.provider}/{meta.model} (language: {meta.language}, "
        f"{status}).",
        "> Statements written by the model cite evidence as `file:start-end`, relative to the "
        "application. Corrections go between the `stc:manual` markers: they take precedence over "
        "the text below and are kept when this page is regenerated.",
        "",
    ]
    for block in page.blocks:
        if isinstance(block, Static):
            out += [block.markdown, ""]
        elif isinstance(block, Part):
            out += [
                f"## {block.title}",
                "",
                manual_block(page.key(block.id), manual.get(page.key(block.id), "")),
                "",
                parts.get(block.id, NOT_GENERATED),
                "",
            ]
    notes_key = page.key(NOTES)
    notes = manual.get(notes_key, "")
    if notes:
        out += ["## Maintainer notes", ""]
    out += [manual_block(notes_key, notes), ""]
    return "\n".join(out).rstrip() + "\n"


def render_orphans(blocks: Mapping[str, str], meta: RenderMeta) -> str:
    out = [
        "# Orphaned notes",
        "",
        "> Notes written for pages or parts that this application no longer has. They are kept "
        "here "
        "so nothing a maintainer wrote is lost; move them where they belong or delete them.",
        "",
    ]
    for key, text in sorted(blocks.items()):
        out += [f"## `{key}`", "", manual_block(key, text), ""]
    return "\n".join(out).rstrip() + "\n"

"""Markdown rendering of a catalog, and recovery of the maintainers' manual corrections (CAT-05).

Every section ends with an empty manual block; whatever a maintainer writes between its markers
survives regeneration and is given to the LLM as authoritative for that section."""

import re
from collections.abc import Mapping
from dataclasses import dataclass

from stc.catalog.model import SECTION_ORDER, SECTION_TITLES, SectionResult

_MANUAL = re.compile(
    r"<!-- stc:manual:begin section=([\w-]+) -->\n?(.*?)\n?<!-- stc:manual:end -->", re.DOTALL
)
_PRESERVED_HEADING = "Manual notes for sections that no longer exist"


@dataclass(frozen=True)
class CatalogMeta:
    application: str
    code_version: str | None
    generated_at: str
    provider: str
    model: str
    language: str
    status: str  # complete | partial


def append_manual(markdown: str, section: str, text: str) -> str:
    """Add `text` to the maintainers' block of `section`, after what is already there. Adding the
    same text twice changes nothing. Raises `KeyError` if the file has no block for the section."""
    addition = text.strip()
    found = False

    def replace(match: re.Match[str]) -> str:
        nonlocal found
        if match.group(1) != section:
            return match.group(0)
        found = True
        body = match.group(2).strip()
        if addition in body:
            return match.group(0)
        merged = f"{body}\n\n{addition}" if body else addition
        return f"<!-- stc:manual:begin section={section} -->\n{merged}\n<!-- stc:manual:end -->"

    updated = _MANUAL.sub(replace, markdown)
    if not found:
        raise KeyError(section)
    return updated


def parse_manual_blocks(markdown: str) -> dict[str, str]:
    """Section id -> text written by maintainers (empty blocks are omitted)."""
    return {
        m.group(1): m.group(2).strip() for m in _MANUAL.finditer(markdown) if m.group(2).strip()
    }


def render_claims(result: SectionResult) -> str:
    lines = []
    for claim in result.claims:
        evidence = ", ".join(f"`{e}`" for e in claim.evidence)
        lines.append(f"- {claim.text} _({claim.confidence} confidence)_ — evidence: {evidence}")
    if result.gaps:
        if lines:
            lines.append("")
        lines.append("**Gaps**")
        lines += [f"- {gap}" for gap in result.gaps]
    return "\n".join(lines) if lines else "_Nothing could be determined._"


def render_catalog(
    meta: CatalogMeta,
    generated: Mapping[str, str],
    manual: Mapping[str, str],
) -> str:
    """`generated` maps section id -> its markdown body (claims or static tables)."""
    out = [
        f"# {meta.application}",
        "",
        f"> Generated by STC from code version `{meta.code_version or 'unknown'}` on "
        f"{meta.generated_at} with {meta.provider}/{meta.model} (language: {meta.language}, "
        f"{meta.status}).",
        "> Every statement cites evidence as `file:start-end`, relative to the application.",
        "> Write corrections between the `stc:manual` markers at the top of a section: they take "
        "precedence over the generated text below and are kept when the catalog is regenerated.",
        "",
    ]
    for section in SECTION_ORDER:
        out += [
            f"## {SECTION_TITLES[section]}",
            "",
            f"<!-- stc:manual:begin section={section} -->",
            manual.get(section, ""),
            "<!-- stc:manual:end -->",
            "",
            generated.get(section, "_Not generated._"),
            "",
        ]
    orphans = {k: v for k, v in manual.items() if k not in SECTION_ORDER}
    if orphans:
        out += [f"## {_PRESERVED_HEADING}", ""]
        for key, body in orphans.items():
            out += [
                f"<!-- stc:manual:begin section={key} -->",
                body,
                "<!-- stc:manual:end -->",
                "",
            ]
    return "\n".join(out).rstrip() + "\n"


def section_bodies(
    results: Mapping[str, SectionResult], static: Mapping[str, str]
) -> dict[str, str]:
    bodies = {section: render_claims(result) for section, result in results.items()}
    bodies.update(static)
    return bodies
